def md5(path: Path) -> str:
    return hashlib.md5(path.read_bytes()).hexdigest()


def job_of(path: Path) -> str:
    job = path.with_name(f"{path.stem}.job.json")
    if not job.exists():
        return "-"
    return str(json.loads(job.read_text(encoding="utf-8")).get("task_id", "-"))


def clean_alpha(img: Image.Image, floor: int = 8) -> Image.Image:
    """Drop the near-transparent fringe a resize leaves, so the keyed edge stays hard."""
    pixels = np.asarray(img).copy()
    pixels[..., 3] = np.where(pixels[..., 3] < floor, 0, pixels[..., 3])
    return Image.fromarray(pixels, "RGBA")


def fit_contain(img: Image.Image, box: tuple[int, int]) -> Image.Image:
    """Scale to fit the box, keep the aspect, centre on a transparent canvas of the box."""
    width, height = img.size
    target_w, target_h = box
    scale = min(target_w / width, target_h / height)
    new = (max(1, int(round(width * scale))), max(1, int(round(height * scale))))
    scaled = img.convert("RGBA").resize(new, Image.LANCZOS)
    canvas = Image.new("RGBA", box, (0, 0, 0, 0))
    canvas.paste(scaled, ((target_w - new[0]) // 2, (target_h - new[1]) // 2))
    return clean_alpha(canvas)


def measure(path: Path) -> dict:
    """The per-file numbers the report carries: box, transparency, ink, bytes, md5."""
    img = Image.open(path).convert("RGBA")
    alpha = np.asarray(img.getchannel("A"))
    return {"pixels": list(img.size), "bytes": path.stat().st_size, "md5": md5(path),
            "transparent_pct": round(100.0 * float((alpha == 0).mean()), 2),
            "ink_pct": round(100.0 * float((alpha > 8).mean()), 2)}


def plan(only: tuple[str, ...] = ()) -> list[tuple[str, str, Path]]:
    """Every master to ship, one row per name: the A1 flat plates claim their name first.

    `only` scopes the copy, never the log - the generation log stays the record of the whole
    family even when one pass ships a subset.
    """
    rows: list[tuple[str, str, Path]] = []
    claimed: set[str] = set()
    for run_id in PLAN_RUNS:
        spec = wave_g.RUNS[run_id]
        for _index, name, _rotate in spec["cells"]:
            if name in claimed:
                continue
            claimed.add(name)
            rows.append((run_id, name, STAGE / "ui" / f"{name}.png"))
    if only:
        rows = [row for row in rows
                if row[1] in only or row[0] in only
                or any(n in only for _i, n, _r in wave_g.RUNS[row[0]]["cells"])]
    return rows


def panel_plan(only: tuple[str, ...] = ()) -> list[tuple[str, str]]:
    """(shipped panel name, run id providing the render) - the A1 re-render wins its three names."""
    sources: dict[str, str] = {}
    for run_id in PLAN_RUNS:
        for table in (PANEL_NAMES_A1, PANEL_NAMES):
            if run_id in table:
                sources.setdefault(table[run_id], run_id)
    rows = sorted(sources.items())
    if only:
        rows = [row for row in rows
                if row[1] in only
                or any(n in only for _i, n, _r in wave_g.RUNS[row[1]]["cells"])]
    return rows


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--stage-only", action="store_true")
    parser.add_argument("--replace", action="store_true")
    parser.add_argument("--only", nargs="*", default=[])
    args = parser.parse_args()

    rows = plan(tuple(args.only))
    all_rows = plan()
    missing = [name for _r, name, path in rows if not path.is_file()]
    if missing:
        print(f"missing cut(s) in staging/phase_g/ui: {', '.join(missing)}")
        return 1
    MASTERS.mkdir(parents=True, exist_ok=True)

    report: dict = {}
    log_rows: list[str] = []
    ## The masters are staged for the whole family (the log is the record of all six), while
    ## `--only` scopes which of them are copied into the project.
    for run_id, name, path in all_rows:
        spec = wave_g.RUNS[run_id]
        box = spec["boxes"][name]
        before = Image.open(path).size
        master = fit_contain(Image.open(path), box)
        route = ("recraft-keyed render cut, contain fit"
                 if run_id in D7_RUNS and run_id not in A1_RUNS else
                 f"recraft-keyed flat plate cut, contain fit, pad "
                 f"{spec.get('pad_share', 0.04):.2f}, canvas {spec.get('aspect', '1:1')} "
                 f"(Amendment 2)")
        report[name] = {"box": list(box), "cut_box": list(before), "route": route}
        master.save(MASTERS / f"{name}.png")
        cell = [i for i, n, _r in spec["cells"] if n == name]
        cell_label = f"{cell[0]} of {len(spec['cells'])}" if cell else "-"
        job = job_of(STAGE / "ui" / f"{spec['panel_name']}.png")
        log_rows.append(f"| `{name}.png` | `{spec['panel_name']}` | {cell_label} | "
                        f"{job} | {box[0]}x{box[1]} | "
                        f"{route} | "
                        f"{spec['subject'].splitlines()[0][-110:]} |")
        print(f"{name:22s} {path.name:26s} {str(before):12s} -> "
              f"{master.size[0]}x{master.size[1]}  {route}")

    if args.list:
        print(f"{len(rows)} master(s) staged in {MASTERS.relative_to(ROOT)}")
        return 0

    if not args.stage_only:
        ui_dir = ASSETS / "ui"
        icons_dir = ASSETS / "icons"
        blocked = 0
        for _run_id, name, _path in rows:
            target = ui_dir / f"{name}.png"
            if (target.exists() and md5(target) != md5(MASTERS / f"{name}.png")
                    and not args.replace):
                print(f"SKIP {name}: exists in the project with different bytes (--replace)")
                blocked += 1
                continue
            ui_dir.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(MASTERS / f"{name}.png", target)
            print(f"  shipped {name}.png -> assets/ui/")
        for panel_name, run_id in panel_plan(tuple(args.only)):
            source = STAGE / "ui" / f"{wave_g.RUNS[run_id]['panel_name']}.png"
            target = icons_dir / f"{panel_name}.png"
            if not source.is_file():
                print(f"SKIP panel {panel_name}: no render in staging")
                blocked += 1
                continue
            icons_dir.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
            print(f"panel {panel_name}.png -> assets/icons/ "
                  f"({Image.open(source).size[0]}x{Image.open(source).size[1]})")
        (ASSETS / "ui" / "generation_log_d7.md").write_text(
            LOG_HEAD + "\n".join(log_rows) + "\n", encoding="utf-8")
        print(f"staged {len(report)} master(s), shipped {len(rows)}; "
              f"log assets/ui/generation_log_d7.md")
        if blocked:
            print(f"{blocked} file(s) refused")
        for report_name, entry in report.items():
            entry.update(measure(MASTERS / f"{report_name}.png"))
        (STAGE / "ui" / "ship_report_d7.json").write_text(json.dumps(report, indent=1),
                                                          encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
