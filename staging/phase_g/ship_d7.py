"""Ship the D7 cockpit-panel-family masters into the Godot project.

Wave D7, `docs/design/UI_CHROME_ASSETS_SPEC.md` section 12. The Phase G lane order is:
render -> `panels.py --detect` -> cut each object on its own box -> key each cut on its own ->
trim and centre (`refit_panels.py`). This step puts those trimmed cuts on their shipped boxes.

* every D7 cut is fitted **contain** on its master box and centred. Section 12 pins the master for
  `ui_cockpit_panel` (928x512), `ui_gauge_face` (240x240) and `ui_status_panel` (1440x1040); the
  two armory boxes are the measured ones recorded in `wave_g.py`'s D7 section.
* the five panel renders ship as provenance panels under `assets/icons/` (`panel_` family,
  ASSET_NAMING_SPEC section 2) - the whole 2048x2048 sheet each family of cells was cut from.
* the generation log is written beside the shipped family from the same run records (AGENTS.md:
  AI art is not CC0).

`ui_gauge_face` already exists in the project (the D6 face); section 12's run 2 is a re-cut under
the same name, so this step needs `--replace` for it. `ui_seg_*`, `ui_compass_*` and
`ui_gauge_needle` are not in the D7 plan and stay byte-identical.

Usage:
    py -3.14 staging/phase_g/ship_d7.py --list
    py -3.14 staging/phase_g/ship_d7.py --stage-only     # masters into staging/phase_g/ui/_masters
    py -3.14 staging/phase_g/ship_d7.py                  # + copy into the project
    py -3.14 staging/phase_g/ship_d7.py --replace
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import numpy as np
from PIL import Image

import wave_g

ROOT = Path(__file__).resolve().parents[2]
STAGE = wave_g.STAGE
ASSETS = ROOT / "vajb-orbit" / "assets"
MASTERS = STAGE / "ui" / "_masters"

D7_RUNS = ("panel_cockpit", "panel_gauge", "panel_armory_console", "panel_armory_plates",
           "panel_status")
## Wave D7-A1/A2, UI_CHROME_ASSETS_SPEC section 12 Amendment 2: the three console panels are
## re-rendered as flat painted plates (their wells are code-drawn at the pinned rects), and those
