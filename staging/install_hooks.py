#!/usr/bin/env python3
"""Install the versioned git hooks into this clone's `.git/hooks/`.

The hooks are host-local by nature, so the versioned half is the script they
call (`staging/pre_push.py`) and this installer. Run once per clone:

    python3 staging/install_hooks.py

The generated `pre-push` shim pins the interpreter that ran the installer
(`sys.executable`), which is the host's project interpreter: `python3` on
Linux, `py -3.14` on Windows. Re-run after moving the clone or changing the
interpreter.
"""

import os
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOOKS = ROOT / ".git" / "hooks"
HOOKS.mkdir(parents=True, exist_ok=True)
HOOK = HOOKS / "pre-push"


def main() -> int:
    if not (ROOT / ".git").exists():
        print("install_hooks: %s is not a git clone" % ROOT)
        return 1
    script = ROOT / "staging" / "pre_push.py"
    if not script.exists():
        print("install_hooks: missing %s" % script)
        return 1
    hook = (
        "#!/bin/sh\n"
        "# Generated by staging/install_hooks.py; edit staging/pre_push.py instead.\n"
        'exec "%s" "%s" "$@"\n' % (sys.executable, script)
    )
    HOOK.write_text(hook)
    HOOK.chmod(HOOK.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print("install_hooks: installed %s -> %s" % (HOOK, script))
    return 0


if __name__ == "__main__":
    sys.exit(main())
